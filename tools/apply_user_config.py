#!/usr/bin/env python3
"""
Turn `user_board.nzk.config` into an ESP-IDF Kconfig fragment.

The generated file is appended to SDKCONFIG_DEFAULTS so that her wifi details
are compiled into the firmware and the tracker joins her network on boot.

Usage:
    python3 tools/apply_user_config.py [--check]

Exit codes:
    0  ok
    1  the config file has a problem (bad key, SSID/password too long, ...)
"""

import argparse
import os
import sys

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_PATH = os.path.join(PROJECT_ROOT, "user_board.nzk.config")
OUT_DIR = os.path.join(PROJECT_ROOT, "boards", "generated")
OUT_PATH = os.path.join(OUT_DIR, "user_config")

# config-file key  ->  (Kconfig symbol, kind)
KEY_MAP = {
    "WIFI_SSID": ("CONFIG_WIFI_SSID", "string"),
    "WIFI_PASSWORD": ("CONFIG_WIFI_PASSWORD", "string"),
    "AP_SSID": ("CONFIG_WIFI_AP_SSID", "string"),
    "AP_PASSWORD": ("CONFIG_WIFI_AP_PASSWORD", "string"),
    "DEVICE_NAME": ("CONFIG_GENERAL_ADVERTISED_NAME", "string"),
    "WIFI_BSSID": ("CONFIG_WIFI_BSSID", "string"),
}

# Wifi limits from the 802.11 spec / WPA2-PSK
SSID_MAX = 32
PSK_MIN = 8
PSK_MAX = 63

problems = []
warnings = []


def parse(path):
    values = {}
    with open(path, "r", encoding="utf-8-sig") as handle:
        for lineno, raw in enumerate(handle, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if "=" not in line:
                problems.append("line %d: expected KEY=VALUE, got %r" % (lineno, line))
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            value = value.strip()

            # Allow inline comments only when clearly separated: VALUE   # note
            if "  #" in value:
                value = value.split("  #", 1)[0].strip()

            if key not in KEY_MAP:
                problems.append(
                    "line %d: unknown setting %r. Valid: %s"
                    % (lineno, key, ", ".join(sorted(KEY_MAP)))
                )
                continue
            values[key] = value
    return values


def validate(values):
    ssid = values.get("WIFI_SSID", "")
    password = values.get("WIFI_PASSWORD", "")
    ap_ssid = values.get("AP_SSID", "")
    ap_password = values.get("AP_PASSWORD", "")
    device = values.get("DEVICE_NAME", "")

    for name, value in (("WIFI_SSID", ssid), ("AP_SSID", ap_ssid), ("DEVICE_NAME", device)):
        if len(value) > SSID_MAX:
            problems.append("%s is %d characters; the maximum is %d" % (name, len(value), SSID_MAX))

    for name, value in (("WIFI_PASSWORD", password), ("AP_PASSWORD", ap_password)):
        if value and not (PSK_MIN <= len(value) <= PSK_MAX):
            problems.append(
                "%s must be %d-%d characters (or empty). It is %d."
                % (name, PSK_MIN, PSK_MAX, len(value))
            )

    if password and not ssid:
        warnings.append("WIFI_PASSWORD is set but WIFI_SSID is empty - the password will be ignored.")

    if ssid and not password:
        warnings.append("WIFI_SSID is set with no password - this is treated as an open network.")

    if ap_ssid and ap_password and ap_ssid == ssid and ap_password == password:
        warnings.append("The fallback AP uses the same name/password as your home wifi.")

    if not ssid:
        warnings.append(
            "No home wifi configured. The tracker will start its own '%s' network instead."
            % (ap_ssid or "EyeTrackVR")
        )

    return ssid, password, ap_ssid, ap_password


def kconfig_escape(value):
    """Escape a value for use inside a Kconfig quoted string."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = parser.parse_args()

    if not os.path.isfile(CONFIG_PATH):
        print("ERROR: %s not found." % CONFIG_PATH)
        return 1

    values = parse(CONFIG_PATH)
    ssid, password, ap_ssid, ap_password = validate(values)

    for warning in warnings:
        print("warning: %s" % warning)
    for problem in problems:
        print("ERROR: %s" % problem)

    if problems:
        print("")
        print("Fix the errors above in user_board.nzk.config and try again.")
        return 1

    if not args.check:
        lines = [
            "# AUTO-GENERATED by tools/apply_user_config.py",
            "# Source: user_board.nzk.config  -- do not edit by hand.",
            "#",
        ]
        for key, value in values.items():
            symbol, _kind = KEY_MAP[key]
            lines.append('%s="%s"' % (symbol, kconfig_escape(value)))

        os.makedirs(OUT_DIR, exist_ok=True)
        with open(OUT_PATH, "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")

    print("")
    if args.check:
        print("(--check: nothing written)")
    else:
        print("Wrote %s" % os.path.relpath(OUT_PATH, PROJECT_ROOT))
    print("")
    print("  home wifi       : %s" % (ssid or "(none - access point only)"))
    print("  home password   : %s" % ("*" * len(password) if password else "(none)"))
    print("  fallback AP     : %s / %s" % (ap_ssid or "(firmware default)", ap_password or "(open)"))
    print("  device name     : %s" % (values.get("DEVICE_NAME") or "(firmware default)"))
    print("")
    return 0


if __name__ == "__main__":
    sys.exit(main())
